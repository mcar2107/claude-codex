/**
 * Вид петли: пробелы между токенами JSON или повтор короткого куска текста внутри строки.
 */
export type LoopKind = 'whitespace' | 'repeat';

/**
 * Ошибка, которой обрывается поток при петле данного вида.
 */
export type LoopError = {
  /**
   * Код ошибки для клиента.
   */
  code: string;

  /**
   * Вид петли в тексте сообщения.
   */
  text: string;
};

/**
 * Состояние лексера аргументов одного вызова инструмента: настолько, чтобы отличить пробелы
 * между токенами JSON от пробелов внутри строк, понять, закрыт ли объект верхнего уровня, и
 * заметить повтор текста в строковом значении.
 */
export type ArgumentsScan = {
  /**
   * Лексер внутри строки — ключа или значения.
   */
  isInString: boolean;

  /**
   * Предыдущий символ строки — `\`: следующий символ экранирован.
   */
  isEscaped: boolean;

  /**
   * Прочитанные шестнадцатеричные цифры escape-последовательности `\uXXXX`; `undefined` — лексер
   * не внутри неё.
   */
  unicodeHex: string | undefined;

  /**
   * Незакрытые контейнеры, `{` или `[`, внутренний — последним: по нему запятая решает, ключ ли
   * следующая строка. Пустая строка — объект верхнего уровня закрыт или не начат.
   */
  containers: string;

  /**
   * Следующая строка будет ключом объекта.
   */
  isKeyNext: boolean;

  /**
   * Текущая строка — ключ объекта.
   */
  isKey: boolean;

  /**
   * Ключ, к которому относится текущее значение: последний прочитанный.
   */
  key: string;

  /**
   * Текст читаемого ключа.
   */
  keyText: string;

  /**
   * Текущее строковое значение — поле с содержимым файла: порог повтора в нём выше.
   */
  isFileContent: boolean;

  /**
   * Последние раскодированные символы текущего значения — не больше максимальной длины повторяющегося куска.
   */
  recent: string[];

  /**
   * Для каждого периода `p` — сколько символов подряд совпало с символом за `p` позиций до него.
   */
  periodRuns: number[];

  /**
   * Пробельных символов подряд вне строк.
   */
  whitespaceRun: number;
};

/**
 * Вызов инструмента, аргументы которого ещё стримятся.
 */
export type ToolCall = {
  /**
   * Элемент `function_call` из `response.output_item.added`.
   */
  item: Record<string, unknown>;

  /**
   * Позиция элемента в выводе ответа.
   */
  outputIndex: unknown;

  /**
   * Аргументы, полученные до сих пор.
   */
  arguments: string;

  /**
   * Лексер аргументов.
   */
  scan: ArgumentsScan;
};

/**
 * Срабатывание сторожа — запись для `tool-guard.json` сессии.
 */
type GuardTrip = {
  /**
   * Когда сработал.
   */
  at: string;

  /**
   * Инструмент, на аргументах которого модель зациклилась.
   */
  tool: string;

  /**
   * Вид петли.
   */
  kind: LoopKind;

  /**
   * Длина серии пробелов на момент срабатывания.
   */
  whitespace: number;

  /**
   * Вложенность незакрытых объектов и массивов аргументов: 0 — модель дописала аргументы и
   * зациклилась вместо конца вызова.
   */
  depth: number;

  /**
   * Вызов закрыт и отдан клиенту; иначе поток оборван ошибкой.
   */
  isRepaired: boolean;
};

export type GuardToolArgumentsOptions = {
  /**
   * Порог серии пробелов вне строк; по умолчанию `WHITESPACE_RUN_LIMIT`.
   */
  limit?: number;

  /**
   * Порог длины повтора внутри строки; по умолчанию `REPEAT_RUN_LIMIT`. В полях с содержимым
   * файла — в `FILE_CONTENT_REPEAT_FACTOR` раз выше.
   */
  repeatLimit?: number;

  /**
   * Вызывается при срабатывании — до того, как поток закроется.
   */
  onTrip?: (trip: GuardTrip) => void;
};
