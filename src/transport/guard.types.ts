/**
 * Состояние лексера аргументов одного вызова инструмента: настолько, чтобы отличить пробелы
 * между токенами JSON от пробелов внутри строк и закрыть незакрытые скобки.
 */
export type ArgumentsScan = {
  /**
   * Лексер внутри строкового значения.
   */
  isInString: boolean;

  /**
   * Предыдущий символ строки — `\`: следующий символ экранирован.
   */
  isEscaped: boolean;

  /**
   * Закрывающие скобки незакрытых объектов и массивов, ближайшая — первой.
   */
  closing: string;

  /**
   * Пробельных символов подряд вне строк.
   */
  whitespaceRun: number;
};

/**
 * Аргументы, которые удалось закрыть после петли.
 */
export type RepairedArguments = {
  /**
   * Что дописать к уже отправленным аргументам, чтобы получился валидный JSON.
   */
  closing: string;

  /**
   * Разобранные аргументы.
   */
  input: Record<string, unknown>;
};

/**
 * Вызов инструмента, аргументы которого ещё стримятся.
 */
export type ToolCall = {
  /**
   * Элемент `function_call` из `response.output_item.added`.
   */
  item: Record<string, unknown>;

  /**
   * Позиция элемента в выводе ответа.
   */
  outputIndex: unknown;

  /**
   * Аргументы, полученные до сих пор.
   */
  arguments: string;

  /**
   * Лексер аргументов.
   */
  scan: ArgumentsScan;
};

/**
 * Срабатывание сторожа — запись для `tool-guard.json` сессии.
 */
type GuardTrip = {
  /**
   * Когда сработал.
   */
  at: string;

  /**
   * Инструмент, на аргументах которого модель зациклилась.
   */
  tool: string;

  /**
   * Длина серии пробелов на момент срабатывания.
   */
  whitespace: number;

  /**
   * Вызов закрыт и отдан клиенту; иначе поток оборван ошибкой.
   */
  isRepaired: boolean;
};

export type GuardToolArgumentsOptions = {
  /**
   * Порог серии пробелов вне строк; по умолчанию `WHITESPACE_RUN_LIMIT`.
   */
  limit?: number;

  /**
   * Вызывается при срабатывании — до того, как поток закроется.
   */
  onTrip?: (trip: GuardTrip) => void;
};
